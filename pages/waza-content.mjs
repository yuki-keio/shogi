const P = (file, rank, type, gote = false) => ({ file, rank, type, gote });
const ALL_FILES = [9, 8, 7, 6, 5, 4, 3, 2, 1];

/** 手筋：盤の一部を切り出した図。駒のあるマスを塗る */
const tesuji = (start, caption, moves, main, extra = {}) => ({
  files: [7, 6, 5, 4, 3], ranks: [3, 4, 5, 6, 7], mark: 'pieces',
  start, caption, moves, main, ...extra,
});

