/** 振り飛車：飛車を振った形を全体図で1枚だけ見せる */
function rookPosition(file) {
  const pieces = [];
  ['香', '桂', '銀', '金', '玉', '金', '銀', '桂', '香'].forEach((type, i) => { pieces.push(P(9 - i, 1, type, true)); pieces.push(P(9 - i, 9, type)); });
  // 歩は「基本の定跡」の図と同じ形。7筋は角のために突き、中飛車以外は6筋の歩で角の通り道を止める。
  // 中飛車は5筋の歩を5五まで伸ばして止める。向かい飛車は振った筋（8筋）の歩を突かない
  const pawnRank = f => f === 7 ? 6 : f === 6 && file !== 5 ? 6 : f === 5 && file === 5 ? 5 : 7;
  for (let f = 9; f >= 1; f--) { pieces.push(P(f, 3, '歩', true)); pieces.push(P(f, pawnRank(f), '歩')); }
  pieces.push(P(8, 2, '飛', true), P(2, 2, '角', true), P(file, 8, '飛'), P(file === 8 ? 7 : 8, file === 8 ? 7 : 8, '角'));
  return {
    files: ALL_FILES, ranks: [1, 2, 3, 4, 5, 6, 7, 8, 9], mark: 'moved',
    start: pieces, focus: [file, 8], main: 0,
    caption: '飛車を振った直後の形です。玉はこれから右へ移して囲います。',
  };
}

